import logging
import uuid
from datetime import datetime
from typing import Any

from flask import Blueprint
from flask_login import current_user, login_required
from sqlalchemy.exc import SQLAlchemyError

from helpers.config import get_config
from helpers.datetime import combine_date_time, parse_iso_date
from helpers.server import _json_error, _json_success

from ..engine import anneal_table, initial_table
from ..extensions import db
from ..models import Activity, Block, Schedule

bp = Blueprint('engine', __name__)

log = logging.getLogger('app')

@bp.route('/generate/<string:sid>', methods=['POST'])
@login_required
def generate_schedule(sid):
    suuid = uuid.UUID(sid)

    schedule = Schedule.query.filter(
        Schedule.owner == current_user,
        Schedule.id == suuid
    ).first()

    if not schedule:
        return _json_error('Schedule (id:{'+sid+'}) does not exist')

    blocks = initial_table(schedule)
    

    try:
        for block in blocks:
            db.session.add(block)
        db.session.commit()

        log.info(f'Successfully added {len(blocks)} blocks from a generated timetable')
        
        blocks = schedule.blocks

        result = [b.serialise() for b in blocks]
        
        log.info(result)

        return _json_success({'blocks':result})
    except SQLAlchemyError:
        db.session.rollback()
        log.exception('Database failure while adding autogenerated blocks.')
        return _json_error('Database failure while adding autogenerated blocks.', 500)


